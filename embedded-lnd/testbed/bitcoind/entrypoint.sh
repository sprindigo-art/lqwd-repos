#!/bin/bash
# regtest bitcoind, shared by both lnd nodes.
#
# Runs in the openvpn container's network namespace, so it is reachable at
# 10.99.0.1 from the Pi over the VPN and at 127.0.0.1 from the server lnd.
set -euo pipefail

DATADIR=/data/bitcoind
CONF=$DATADIR/bitcoin.conf
RPCUSER="${BITCOIND_RPCUSER:-lnd}"
RPCPASS="${BITCOIND_RPCPASS:?set BITCOIND_RPCPASS - generated by 61-testbed-up.sh}"

mkdir -p "$DATADIR"

# Written on every start so a changed password or VPN subnet takes effect.
#
# Network-specific options (rpcbind, rpcallowip, rpcport, zmq*, txindex,
# fallbackfee) MUST live under the [regtest] section - Bitcoin Core refuses to
# start otherwise: "Config setting for -rpcbind only applied on regtest network
# when in [regtest] section."
cat > "$CONF" <<CONF
regtest=1
server=1
daemon=0
printtoconsole=1

rpcuser=$RPCUSER
rpcpassword=$RPCPASS

[regtest]
# Bind everywhere inside this network namespace, but authorise only loopback
# and the VPN. The namespace is not reachable from outside the host, and the
# only published port on it is udp/1194.
rpcbind=0.0.0.0
rpcport=18443
rpcallowip=127.0.0.1
rpcallowip=10.99.0.0/24

txindex=1

# lnd needs these to learn about new blocks and transactions promptly.
# ZMQ has no authentication of its own; it is publish-only and confined to
# this namespace plus the VPN.
zmqpubrawblock=tcp://0.0.0.0:28332
zmqpubrawtx=tcp://0.0.0.0:28333

# regtest has no fee estimation data; lnd needs a fallback.
fallbackfee=0.0001
CONF

echo ">>> starting bitcoind (regtest)"
exec bitcoind -conf="$CONF" -datadir="$DATADIR"
